#!/usr/bin/env node
/**
 * Writes the public project API key into /assets/posthog-config.js from env.
 *
 * Env:
 *   POSTHOG_PROJECT_API_KEY  (phc_...)  required
 *   POSTHOG_API_HOST         optional, default https://us.i.posthog.com
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { resolvePostHogEnv } from "./posthog-env.mjs";

const { root, apiHost, projectApiKey: envKey } = resolvePostHogEnv();

function keyFromConfigFile() {
  const path = join(root, "assets/posthog-config.js");
  if (!existsSync(path)) return "";
  const m = readFileSync(path, "utf8").match(/key:\s*"((?:phc_)[^"]+)"/);
  return m?.[1] || "";
}

const key = (envKey || keyFromConfigFile()).trim();
const host = apiHost;

if (!key || !key.startsWith("phc_")) {
  console.error(
    "Set POSTHOG_PROJECT_API_KEY to your PostHog project API key (starts with phc_)."
  );
  process.exit(1);
}

const contents = `/**
 * Public PostHog project key (write-only). Safe to ship in the browser.
 * Generated by scripts/apply-posthog-config.mjs — do not put personal API keys here.
 */
window.__POSTHOG_CONFIG__ = {
  key: ${JSON.stringify(key)},
  host: ${JSON.stringify(host)},
};
`;

writeFileSync(join(root, "assets/posthog-config.js"), contents);
console.log(`Wrote assets/posthog-config.js (host=${host})`);
